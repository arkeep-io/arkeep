//go:build ignore

// download_deps.go is a standalone Go script (not part of any module) that
// downloads the restic and rclone binaries into agent/internal/restic/bin/.
// It is invoked by the Taskfile and by GoReleaser's before hook.
//
// Usage:
//
//	# Current platform only (Taskfile / local development)
//	go run ./scripts/download_deps.go
//
//	# All release platforms (GoReleaser before hook)
//	go run ./scripts/download_deps.go --all-platforms
//
// Using a Go script instead of shell/cmd.exe commands guarantees identical
// behaviour on Linux, macOS, and Windows without any external tools beyond
// the Go toolchain itself.
//
// restic archives are downloaded through the GitHub API, authenticated with
// GITHUB_TOKEN when it is set (CI and GoReleaser set it; locally it is
// optional), and transient failures are retried.
//
// Restic release format per platform:
//   - Linux/macOS: restic_<ver>_<os>_<arch>.bz2  (single binary, bzip2-compressed)
//   - Windows:     restic_<ver>_windows_<arch>.zip (zip containing restic.exe)
//
// Rclone release format (all platforms):
//   - rclone-v<ver>-<os>-<arch>.zip (zip containing <archive-name>/rclone[.exe])
//
// Versions and the SHA-256 of every archive come from deps.json, generated by
// update-deps-pins.sh from the GPG-verified upstream SHA256SUMS (ADR 0013).
// An archive whose digest differs, or that has no pinned digest, fails the
// download.
package main

import (
	"archive/zip"
	"bytes"
	"compress/bzip2"
	"context"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"time"
)

const (
	binDir   = "internal/restic/bin"
	pinsFile = "scripts/deps.json"
)

// pinnedTool is one entry of deps.json.
type pinnedTool struct {
	Version string            `json:"version"`
	SHA256  map[string]string `json:"sha256"`
}

// Set by loadPins from deps.json.
var (
	resticVersion string
	rcloneVersion string
	archiveSHA256 = map[string]string{}
)

func loadPins() error {
	data, err := os.ReadFile(pinsFile)
	if err != nil {
		return err
	}
	var pins struct {
		Restic pinnedTool `json:"restic"`
		Rclone pinnedTool `json:"rclone"`
	}
	if err := json.Unmarshal(data, &pins); err != nil {
		return fmt.Errorf("parse %s: %w", pinsFile, err)
	}
	if pins.Restic.Version == "" || pins.Rclone.Version == "" {
		return fmt.Errorf("%s: missing restic or rclone version", pinsFile)
	}
	resticVersion, rcloneVersion = pins.Restic.Version, pins.Rclone.Version
	for _, tool := range []pinnedTool{pins.Restic, pins.Rclone} {
		for name, sum := range tool.SHA256 {
			archiveSHA256[name] = sum
		}
	}
	return nil
}

// platform represents a target OS/arch combination for binary downloads.
type platform struct {
	goos   string
	goarch string
}

// releasePlatforms lists all platforms for which binaries are embedded in the
// agent for release builds. Must stay in sync with the goarch/goos matrices
// in .goreleaser.yml.
//
// Note: windows/arm64 is excluded because restic does not publish a
// windows/arm64 binary.
var releasePlatforms = []platform{
	{"linux", "amd64"},
	{"linux", "arm64"},
	{"linux", "arm"},
	{"linux", "mips"},
	{"linux", "mipsle"},
	{"darwin", "amd64"},
	{"darwin", "arm64"},
	{"windows", "amd64"},
}

func main() {
	allPlatforms := false
	for _, arg := range os.Args[1:] {
		if arg == "--all-platforms" {
			allPlatforms = true
		}
	}

	if err := loadPins(); err != nil {
		fatalf("load pins: %v", err)
	}

	if err := os.MkdirAll(binDir, 0o755); err != nil {
		fatalf("create bin dir: %v", err)
	}

	var platforms []platform
	if allPlatforms {
		fmt.Println("Downloading binaries for all release platforms...")
		platforms = releasePlatforms
	} else {
		platforms = []platform{{runtime.GOOS, runtime.GOARCH}}
	}

	for _, p := range platforms {
		if err := downloadRestic(p.goos, p.goarch); err != nil {
			fatalf("restic %s/%s: %v", p.goos, p.goarch, err)
		}
		if err := downloadRclone(p.goos, p.goarch); err != nil {
			fatalf("rclone %s/%s: %v", p.goos, p.goarch, err)
		}
	}
}

// ─── restic ──────────────────────────────────────────────────────────────────

func downloadRestic(goos, goarch string) error {
	resticOS := normalizeOS(goos)
	ext := exeExtFor(goos)
	out := filepath.Join(binDir, fmt.Sprintf("restic_%s_%s%s", resticOS, goarch, ext))

	if fileExists(out) {
		fmt.Printf("restic already present: %s\n", out)
		return nil
	}

	fmt.Printf("Downloading restic %s for %s/%s...\n", resticVersion, resticOS, goarch)

	if goos == "windows" {
		return downloadResticZip(resticOS, goarch, out)
	}
	return downloadResticBz2(resticOS, goarch, out)
}

// resticReleaseAPI is the GitHub API endpoint of a restic release, by version.
const resticReleaseAPI = "https://api.github.com/repos/restic/restic/releases/tags/v%s"

// resticAssets maps the archive names of the pinned restic release to their
// GitHub API download URLs. Filled on first use by resticAssetURL.
var resticAssets map[string]string

// resticAssetURL returns the GitHub API URL of archive in the pinned restic
// release. restic is downloaded through api.github.com rather than the
// github.com/.../releases/download links: GitHub sheds anonymous traffic to
// those links when under load (an immediate 504, see the November 2026
// incident), while the API accepts the GITHUB_TOKEN available in CI. The
// archive is still checked against its pinned SHA-256, wherever it comes from.
func resticAssetURL(archive string) (string, error) {
	if resticAssets == nil {
		data, err := download(fmt.Sprintf(resticReleaseAPI, resticVersion), "application/vnd.github+json")
		if err != nil {
			return "", err
		}
		var release struct {
			Assets []struct {
				Name string `json:"name"`
				URL  string `json:"url"`
			} `json:"assets"`
		}
		if err := json.Unmarshal(data, &release); err != nil {
			return "", fmt.Errorf("parse restic release v%s: %w", resticVersion, err)
		}
		resticAssets = map[string]string{}
		for _, a := range release.Assets {
			resticAssets[a.Name] = a.URL
		}
	}
	url, ok := resticAssets[archive]
	if !ok {
		return "", fmt.Errorf("restic release v%s has no asset %s", resticVersion, archive)
	}
	return url, nil
}

// fetchRestic downloads archive from the pinned restic release.
func fetchRestic(archive string) ([]byte, error) {
	url, err := resticAssetURL(archive)
	if err != nil {
		return nil, err
	}
	return fetch(archive, url, "application/octet-stream")
}

func downloadResticBz2(resticOS, goarch, out string) error {
	archive := fmt.Sprintf("restic_%s_%s_%s.bz2", resticVersion, resticOS, goarch)

	data, err := fetchRestic(archive)
	if err != nil {
		return err
	}

	decompressed, err := io.ReadAll(bzip2.NewReader(bytes.NewReader(data)))
	if err != nil {
		return fmt.Errorf("decompress bzip2: %w", err)
	}

	return writeExecutable(out, decompressed)
}

func downloadResticZip(resticOS, goarch, out string) error {
	archiveName := fmt.Sprintf("restic_%s_%s_%s", resticVersion, resticOS, goarch)

	data, err := fetchRestic(archiveName + ".zip")
	if err != nil {
		return err
	}

	// The exe inside the zip is named restic_<ver>_windows_<arch>.exe —
	// search by .exe suffix since there is exactly one exe in the archive
	// and the full name includes the version string (changes across releases).
	extracted, err := extractFromZipBySuffix(data, ".exe")
	if err != nil {
		return fmt.Errorf("extract from zip: %w", err)
	}

	return writeExecutable(out, extracted)
}

// ─── rclone ──────────────────────────────────────────────────────────────────

func downloadRclone(goos, goarch string) error {
	rcloneOS := rclonePlatform(goos)
	ext := exeExtFor(goos)
	out := filepath.Join(binDir, fmt.Sprintf("rclone_%s_%s%s", goos, goarch, ext))

	if fileExists(out) {
		fmt.Printf("rclone already present: %s\n", out)
		return nil
	}

	archiveName := fmt.Sprintf("rclone-v%s-%s-%s", rcloneVersion, rcloneOS, goarch)
	url := fmt.Sprintf("https://downloads.rclone.org/v%s/%s.zip", rcloneVersion, archiveName)

	fmt.Printf("Downloading rclone %s for %s/%s...\n", rcloneVersion, rcloneOS, goarch)

	data, err := fetch(archiveName+".zip", url, "")
	if err != nil {
		return err
	}

	// rclone zip contains a subdirectory: <archiveName>/rclone[.exe]
	target := archiveName + "/rclone" + ext
	extracted, err := extractFromZip(data, target)
	if err != nil {
		return fmt.Errorf("extract from zip: %w", err)
	}

	return writeExecutable(out, extracted)
}

// ─── helpers ─────────────────────────────────────────────────────────────────

// retryDelays are the waits before each new attempt at a download that failed
// transiently (network error, 5xx or 429).
var retryDelays = []time.Duration{5 * time.Second, 15 * time.Second, 30 * time.Second}

// httpClient bounds each attempt, so a stalled download is retried instead of
// hanging the build.
var httpClient = &http.Client{Timeout: 5 * time.Minute}

// githubAPIHost is the only host that receives GITHUB_TOKEN. The client drops
// the Authorization header when the API redirects to the asset storage host.
const githubAPIHost = "api.github.com"

// fetch downloads url (with the given Accept header, if any) and checks the
// body against the pinned digest of name, the archive file name in deps.json.
// An unpinned file is an error, not a warning; a digest mismatch is never
// retried.
func fetch(name, url, accept string) ([]byte, error) {
	want, ok := archiveSHA256[name]
	if !ok {
		return nil, fmt.Errorf("no pinned SHA-256 for %s in %s: run scripts/update-deps-pins.sh", name, pinsFile)
	}

	data, err := download(url, accept)
	if err != nil {
		return nil, err
	}

	sum := sha256.Sum256(data)
	if got := hex.EncodeToString(sum[:]); got != want {
		return nil, fmt.Errorf("%s: SHA-256 mismatch: got %s, want %s", name, got, want)
	}
	return data, nil
}

// download gets url, retrying transient failures after each of retryDelays.
func download(url, accept string) ([]byte, error) {
	for attempt := 0; ; attempt++ {
		data, transient, err := get(url, accept)
		if err == nil {
			return data, nil
		}
		if !transient || attempt == len(retryDelays) {
			return nil, err
		}
		fmt.Printf("%v; retrying in %s...\n", err, retryDelays[attempt])
		time.Sleep(retryDelays[attempt])
	}
}

// get downloads url once. Requests to the GitHub API carry GITHUB_TOKEN when
// it is set (CI, GoReleaser), so they are not subject to the anonymous rate
// limit of 60 requests per hour per IP. transient reports whether a failure
// is worth retrying: a network error, a truncated body, a 5xx or a 429. Any
// other status (404 for a wrong version, 403) fails at once.
func get(url, accept string) (data []byte, transient bool, err error) {
	req, err := http.NewRequestWithContext(context.Background(), http.MethodGet, url, nil)
	if err != nil {
		return nil, false, fmt.Errorf("GET %s: %w", url, err)
	}
	if accept != "" {
		req.Header.Set("Accept", accept)
	}
	token := os.Getenv("GITHUB_TOKEN")
	if token != "" && req.URL.Host == githubAPIHost {
		req.Header.Set("Authorization", "Bearer "+token)
	}

	resp, err := httpClient.Do(req)
	if err != nil {
		return nil, true, fmt.Errorf("GET %s: %w", url, err)
	}
	defer func() { _ = resp.Body.Close() }()

	if resp.StatusCode != http.StatusOK {
		transient = resp.StatusCode >= 500 || resp.StatusCode == http.StatusTooManyRequests
		err = fmt.Errorf("GET %s: unexpected status %s", url, resp.Status)
		if resp.StatusCode == http.StatusForbidden && req.URL.Host == githubAPIHost && token == "" {
			err = fmt.Errorf("%w (anonymous GitHub API rate limit: set GITHUB_TOKEN)", err)
		}
		return nil, transient, err
	}

	data, err = io.ReadAll(resp.Body)
	if err != nil {
		return nil, true, fmt.Errorf("read body: %w", err)
	}
	return data, false, nil
}

func extractFromZip(data []byte, target string) ([]byte, error) {
	r, err := zip.NewReader(bytes.NewReader(data), int64(len(data)))
	if err != nil {
		return nil, err
	}

	target = filepath.ToSlash(target)
	for _, f := range r.File {
		if filepath.ToSlash(f.Name) == target {
			rc, err := f.Open()
			if err != nil {
				return nil, err
			}
			defer func() { _ = rc.Close() }()
			return io.ReadAll(rc)
		}
	}

	var names []string
	for _, f := range r.File {
		names = append(names, f.Name)
	}
	return nil, fmt.Errorf("file %q not found in zip; available: %s", target, strings.Join(names, ", "))
}

func extractFromZipBySuffix(data []byte, suffix string) ([]byte, error) {
	r, err := zip.NewReader(bytes.NewReader(data), int64(len(data)))
	if err != nil {
		return nil, err
	}

	suffix = strings.ToLower(suffix)
	for _, f := range r.File {
		if strings.HasSuffix(strings.ToLower(f.Name), suffix) {
			rc, err := f.Open()
			if err != nil {
				return nil, err
			}
			defer func() { _ = rc.Close() }()
			return io.ReadAll(rc)
		}
	}

	var names []string
	for _, f := range r.File {
		names = append(names, f.Name)
	}
	return nil, fmt.Errorf("no file ending with %q found in zip; available: %s", suffix, strings.Join(names, ", "))
}

func writeExecutable(path string, data []byte) error {
	if err := os.WriteFile(path, data, 0o755); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	fmt.Printf("Written: %s\n", path)
	return nil
}

func fileExists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}

func exeExtFor(goos string) string {
	if goos == "windows" {
		return ".exe"
	}
	return ""
}

func normalizeOS(goos string) string {
	switch goos {
	case "darwin":
		return "darwin"
	case "windows":
		return "windows"
	default:
		return "linux"
	}
}

func rclonePlatform(goos string) string {
	switch goos {
	case "darwin":
		return "osx"
	case "windows":
		return "windows"
	default:
		return "linux"
	}
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "error: "+format+"\n", args...)
	os.Exit(1)
}
